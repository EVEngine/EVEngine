void same(const SimParticle& actual, const SimParticle& expected) {
    REQUIRE(actual.kind == expected.kind);
    REQUIRE(actual.flags == expected.flags);
    REQUIRE(actual.color == expected.color);
    REQUIRE(std::abs(actual.x - expected.x) < 1e-10);
    REQUIRE(std::abs(actual.y - expected.y) < 1e-10);
    REQUIRE(std::abs(actual.vx - expected.vx) < 1e-10);
    REQUIRE(std::abs(actual.vy - expected.vy) < 1e-10);
    REQUIRE(std::abs(actual.life - expected.life) < 1e-10);
    REQUIRE(std::abs(actual.max - expected.max) < 1e-10);
    REQUIRE(std::abs(actual.size - expected.size) < 1e-10);
    REQUIRE(std::abs(actual.seed - expected.seed) < 1e-10);
    REQUIRE(std::abs(actual.delay - expected.delay) < 1e-10);
}
