#!/usr/bin/env python3
"""Compile the SCAD material groups to portable Y-up, metre-scale OBJ meshes.

Requires OpenSCAD on PATH only when rebuilding. Runtime uses checked-in OBJs.
The geometry is OpenSCAD output; this script only changes axes/units and format.
"""

import argparse
from pathlib import Path
import struct
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--openscad", default="openscad")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent
    target = root.parent / "assets" / "architecture"
    target.mkdir(parents=True, exist_ok=True)
    for part in ["stone", "metal", "glass", "wood", "fabric", "ceramic", "soil"]:
        with tempfile.TemporaryDirectory() as staging:
            stl = Path(staging) / "part.stl"
            subprocess.run(
                [
                    args.openscad,
                    "--hardwarnings",
                    "--export-format",
                    "binstl",
                    "-D",
                    f'part="{part}"',
                    "-o",
                    str(stl),
                    str(root / "balcony.scad"),
                ],
                check=True,
            )
            data = stl.read_bytes()
            (count,) = struct.unpack_from("<I", data, 80)
            if len(data) != 84 + count * 50:
                raise ValueError("Malformed binary STL")
            lines = ["# Generated by scad/build.py from balcony.scad; metres, Y-up."]
            for i in range(count):
                values = struct.unpack_from("<12f", data, 84 + i * 50)
                for j in [3, 6, 9]:
                    x, y, z = values[j : j + 3]
                    lines.append(f"v {x / 1000:.7f} {z / 1000:.7f} {-y / 1000:.7f}")
                n = i * 3 + 1
                lines.append(f"f {n} {n + 1} {n + 2}")
            (target / f"{part}.obj").write_text("\n".join(lines) + "\n")
            print(f"{part}: {count} triangles")


if __name__ == "__main__":
    main()
