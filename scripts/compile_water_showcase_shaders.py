#!/usr/bin/env python3
"""Compile the two water-showcase variants and portable script word arrays."""

from pathlib import Path
import shutil
import struct
import subprocess

import utf8_stdio

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "examples" / "stylized-water-shore" / "shaders"


def main() -> None:
    compiler = shutil.which("glslc")
    if not compiler:
        raise SystemExit("glslc from the Vulkan SDK is required to regenerate water shaders")
    for name, defines in (("stylized-water-shore", []), ("interactive-shallow-water", ["-DINTERACTION=1"])):
        folder = ROOT / "examples" / name
        arrays = []
        for stage in ("vert", "frag"):
            output = folder / "shaders" / f"water.{stage}.spv"
            output.parent.mkdir(parents=True, exist_ok=True)
            subprocess.run([compiler, *defines, str(SOURCE / f"water.{stage}"), "-o", str(output)], check=True)
            binary = output.read_bytes()
            words = struct.unpack(f"<{len(binary) // 4}I", binary)
            arrays.append("[\n" + ",\n".join(
                "    " + ",".join(str(v) for v in words[i:i + 16]) for i in range(0, len(words), 16)
            ) + "\n]")
        script = "// Generated by scripts/compile_water_showcase_shaders.py; do not edit.\n"
        script += "function installWaterSurface(shader) {\n"
        script += "    local result=gfx.replaceShaderFromSpv(shader," + ",".join(arrays) + ");\n"
        script += '    if(!result.ok) throw "water surface shader: "+result.status.summary;\n}\n'
        (folder / "water_shader.nut").write_text(script, encoding="utf-8")
        subprocess.run([compiler, str(SOURCE / "terrain.frag"), "-o",
                        str(folder / "shaders" / "terrain.frag.spv")], check=True)
        subprocess.run([compiler, str(SOURCE / "stone.frag"), "-o",
                        str(folder / "shaders" / "stone.frag.spv")], check=True)
        subprocess.run([compiler, str(SOURCE / "sky.frag"), "-o",
                        str(folder / "shaders" / "sky.frag.spv")], check=True)
        subprocess.run([compiler, str(SOURCE / "ridge.frag"), "-o",
                        str(folder / "shaders" / "ridge.frag.spv")], check=True)
        print(f"Compiled {name} water shaders")


if __name__ == "__main__":
    utf8_stdio.enable_utf8_stdio()
    main()
