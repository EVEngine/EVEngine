#!/usr/bin/env python3
"""Embed cmake/sdk/asset-kits/catalog.json as a C++ raw-string include.

Writes src/engine/devtools/AssetKitsEmbedded.inc so MCP tools can serve the
catalog without a runtime share/ path. Re-run after editing catalog.json:

    python3 scripts/embed_asset_kits.py

scripts/tests/test_asset_kits.py fails when the include drifts from the JSON.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_CATALOG = ROOT / "cmake" / "sdk" / "asset-kits" / "catalog.json"
DEFAULT_OUT = ROOT / "src" / "engine" / "devtools" / "AssetKitsEmbedded.inc"


def choose_delimiter(content: str) -> str:
    delim = "evekit"
    for _ in range(33):
        if f"){delim}\"" not in content:
            return delim
        delim += "x"
    raise RuntimeError("no raw-string delimiter fits the catalog")


def render_inc(catalog_text: str) -> str:
    # Keep a trailing newline so diff/editors stay calm; strip only CRs.
    body = catalog_text.replace("\r\n", "\n").replace("\r", "\n")
    if not body.endswith("\n"):
        body += "\n"
    delim = choose_delimiter(body)
    return (
        "// Generated by scripts/embed_asset_kits.py — do not edit by hand.\n"
        "// Source: cmake/sdk/asset-kits/catalog.json\n"
        f'static constexpr std::string_view kEmbeddedAssetKitCatalog = R"{delim}('
        f"{body}"
        f'){delim}";\n'
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog", type=Path, default=DEFAULT_CATALOG)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit 1 if the include is missing or out of date (no write).",
    )
    args = parser.parse_args(argv)
    catalog_text = args.catalog.read_text(encoding="utf-8")
    rendered = render_inc(catalog_text)
    if args.check:
        if not args.out.is_file():
            print(f"missing {args.out}", file=sys.stderr)
            return 1
        current = args.out.read_text(encoding="utf-8")
        if current != rendered:
            print(f"stale {args.out}; run: python3 scripts/embed_asset_kits.py", file=sys.stderr)
            return 1
        print(f"OK {args.out}")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    if args.out.is_file() and args.out.read_text(encoding="utf-8") == rendered:
        print(f"unchanged {args.out}")
        return 0
    args.out.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    import utf8_stdio

    utf8_stdio.enable_utf8_stdio()
    raise SystemExit(main())
