#!/usr/bin/env python3
"""Compile ocean GLSL and embed the matching WebGPU shader sources."""
from pathlib import Path
import shutil
import subprocess
import tempfile

from compile_graphics_water_shaders import spv_to_inc
import utf8_stdio


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    shaders = root / "src/modules/fluids/shaders"
    compiler = shutil.which("glslangValidator")
    if not compiler:
        raise SystemExit("glslangValidator is required")
    with tempfile.TemporaryDirectory(prefix="eve-ocean-shaders-") as temporary:
        for stage in ("vert", "frag"):
            output = Path(temporary) / f"ocean.{stage}.spv"
            subprocess.run([compiler, "-V", str(shaders / f"ocean.{stage}"), "-o", str(output)], check=True)
            spv_to_inc(output, f"ocean_{stage}_spv", shaders / f"ocean_{stage}_spv.inc")
        for stage in ("vert", "frag"):
            output = Path(temporary) / f"ocean_spray.{stage}.spv"
            subprocess.run([compiler, "-V", str(shaders / f"ocean_spray.{stage}"), "-o", str(output)], check=True)
            spv_to_inc(output, f"ocean_spray_{stage}_spv", shaders / f"ocean_spray_{stage}_spv.inc")
        for name in ("ocean_evolve", "ocean_fft", "ocean_pack"):
            output = Path(temporary) / f"{name}.spv"
            subprocess.run([compiler, "-V", str(shaders / f"{name}.comp"), "-o", str(output)], check=True)
            spv_to_inc(output, f"{name}_spv", shaders / f"{name}_spv.inc")
        output = Path(temporary) / "ocean_gpu.vert.spv"
        subprocess.run([compiler, "-V", str(shaders / "ocean_gpu.vert"), "-o", str(output)], check=True)
        spv_to_inc(output, "ocean_gpu_vert_spv", shaders / "ocean_gpu_vert_spv.inc")
    vertex = (shaders / "ocean.vert.wgsl").read_text(encoding="utf-8")
    fragment = (shaders / "ocean.frag.wgsl").read_text(encoding="utf-8")
    (shaders / "OceanWgsl.h").write_text(
        "#pragma once\n// Generated by scripts/compile_ocean_shaders.py.\n"
        "namespace eve::fluids::shaders {\n"
        f'inline constexpr char oceanVertex[] = R"wgsl({vertex})wgsl";\n'
        f'inline constexpr char oceanFragment[] = R"wgsl({fragment})wgsl";\n'
        "}\n", encoding="utf-8")


    spray_vertex = (shaders / "ocean_spray.vert.wgsl").read_text(encoding="utf-8")
    spray_fragment = (shaders / "ocean_spray.frag.wgsl").read_text(encoding="utf-8")
    (shaders / "OceanSprayWgsl.h").write_text(
        "#pragma once\n// Generated by scripts/compile_ocean_shaders.py.\n"
        "namespace eve::fluids::shaders {\n"
        f'inline constexpr char sprayVertex[] = R"wgsl({spray_vertex})wgsl";\n'
        f'inline constexpr char sprayFragment[] = R"wgsl({spray_fragment})wgsl";\n'
        "}\n", encoding="utf-8")


if __name__ == "__main__":
    utf8_stdio.enable_utf8_stdio()
    main()
